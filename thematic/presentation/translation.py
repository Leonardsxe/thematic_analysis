def t(key: str, lang: str = "en", **kwargs: str) -> str:
    """
    Pure-Python translation lookup — no Streamlit dependency.

    Parameters
    ----------
    key:    Translation key.
    lang:   ISO 639-1 code (``"en"`` or ``"es"``).
    kwargs: Optional ``str.format`` arguments, e.g. ``t("active_project_info", lang="es", name="X")``.
    """
    text = TRANSLATIONS.get(lang, TRANSLATIONS["en"]).get(key, key)
    return text.format(**kwargs) if kwargs else text


def ts(key: str, **kwargs: str) -> str:
    """
    Streamlit-aware helper: reads language from ``st.session_state["language"]``.

    Import only inside page files so this module stays testable without Streamlit.
    """
    import streamlit as _st  # local import — keeps module importable outside Streamlit
    lang = _st.session_state.get("language", "en")
    return t(key, lang=lang, **kwargs)